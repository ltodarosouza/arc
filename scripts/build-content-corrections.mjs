/**
 * Writes an additive migration for editorial corrections to already-applied
 * Cálculo II draft batches.  Initial batch migrations are historical records:
 * never regenerate or edit them after they have been applied.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { enrichEditorial } from '../content/calculus-2/editorial.mjs';

const check = process.argv.includes('--check');
const outputPath =
  'supabase/migrations/20260908120000_improve_calc2_draft_editorial_quality.sql';
const uuid = (group, value) =>
  `${group}0000000-0000-4000-8000-${String(value).padStart(12, '0')}`;
const quote = (value) => "'" + String(value).replaceAll("'", "''") + "'";
const lines = [
  '-- Generated by scripts/build-content-corrections.mjs. Do not edit by hand.',
  '-- Safe, additive editorial update for batches #62–#68 when present as drafts.',
  '-- It improves wording, hints and commented solutions; it does not publish content or change answer keys.',
  'begin;',
];

let total = 0;
for (const [issue, count] of [
  [62, 20],
  [63, 12],
  [64, 10],
  [65, 12],
  [66, 12],
  [67, 5],
  [68, 13],
]) {
  const { default: batch } = await import(
    `../content/calculus-2/batch-${issue}.mjs`
  );
  assert.equal(batch.length, count);
  for (const [index, sourceItem] of batch.entries()) {
    const item = enrichEditorial(sourceItem);
    const number = issue * 100 + index;
    const questionId = uuid(4, number);
    total++;

    lines.push(
      `update public.questions set statement_markdown=${quote(item.statement)} where id=${quote(questionId)} and publication_status='draft';`,
      `update public.question_solutions set final_answer_markdown=${quote(item.options[0])}, explanation_markdown=${quote(item.explanation)} where question_id=${quote(questionId)};`,
    );

    item.hints.forEach((hint, hintIndex) =>
      lines.push(
        `insert into public.question_hints (id, question_id, content_markdown, sort_order) select ${quote(uuid(6, number * 10 + hintIndex))}, ${quote(questionId)}, ${quote(hint)}, ${hintIndex + 1} where exists (select 1 from public.questions where id=${quote(questionId)} and publication_status='draft') on conflict (question_id, sort_order) do update set content_markdown=excluded.content_markdown;`,
      ),
    );

    item.solutionSteps.forEach((step, stepIndex) =>
      lines.push(
        `insert into public.question_solution_steps (id, question_id, title, content_markdown, sort_order) select ${quote(uuid(7, number * 10 + stepIndex))}, ${quote(questionId)}, ${quote(step.title)}, ${quote(step.content)}, ${stepIndex + 1} where exists (select 1 from public.questions where id=${quote(questionId)} and publication_status='draft') on conflict (question_id, sort_order) do update set title=excluded.title, content_markdown=excluded.content_markdown;`,
      ),
    );
  }
}
lines.push('commit;', '');
const text = lines.join('\n');
if (check)
  assert.equal(
    readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n'),
    text,
    `${outputPath} is stale`,
  );
else writeFileSync(outputPath, text);
console.log(`${total} draft questions receive additive editorial corrections.`);
