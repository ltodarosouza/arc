import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import katex from 'katex';

const check = process.argv.includes('--check');
const uuid = (group, value) =>
  `${group}0000000-0000-4000-8000-${String(value).padStart(12, '0')}`;
const quote = (value) =>
  value === null ? 'null' : "'" + String(value).replaceAll("'", "''") + "'";
const subject = uuid(2, 1);
const taxonomy = {
  partes: [11, 1, 'integracao-por-partes', 'Integração por partes'],
  fracoes: [101, 1, 'fracoes-parciais', 'Funções racionais e frações parciais'],
  trigonometricas: [
    102,
    1,
    'integrais-trigonometricas',
    'Integrais trigonométricas',
  ],
  infinitos: [104, 103, 'intervalos-infinitos', 'Intervalos infinitos'],
  descontinuidades: [
    105,
    103,
    'descontinuidades',
    'Integrandos com descontinuidade',
  ],
  'limites-sequencias': [
    107,
    106,
    'limite-de-sequencia',
    'Limite de uma sequência',
  ],
  monotonicidade: [
    108,
    106,
    'monotonicidade-e-convergencia',
    'Monotonicidade e convergência',
  ],
  geometricas: [6, 5, 'series-geometricas', 'Séries geométricas'],
  convergencia: [
    109,
    5,
    'convergencia-e-divergencia',
    'Convergência e divergência',
  ],
  testes: [
    110,
    5,
    'testes-de-convergencia',
    'Testes de comparação, razão e raiz',
  ],
  alternadas: [111, 5, 'series-alternadas', 'Séries alternadas'],
  potencias: [112, 5, 'series-de-potencias', 'Séries de potências'],
  taylor: [113, 5, 'taylor-e-maclaurin', 'Séries de Taylor e Maclaurin'],
};
function output(path, text) {
  if (check)
    assert.equal(
      readFileSync(path, 'utf8').replaceAll('\r\n', '\n'),
      text,
      `${path} is stale`,
    );
  else writeFileSync(path, text);
}
const all = [];
for (const [issue, count] of [
  [62, 20],
  [63, 12],
  [64, 10],
  [65, 12],
  [66, 12],
  [67, 5],
  [68, 13],
]) {
  const { default: batch } = await import(
    `../content/calculus-2/batch-${issue}.mjs`
  );
  assert.equal(batch.length, count);
  const sql = [
    '-- Generated by scripts/build-content-batches.mjs. Do not edit by hand.',
    '-- Original drafts: independent technical/pedagogical and rights approval remain pending.',
    '-- Applying this migration does NOT publish these questions.',
    'begin;',
  ];
  const insert = (table, columns, values) =>
    sql.push(
      `insert into public.${table} (${columns}) values (${values.map(quote).join(', ')}) on conflict do nothing;`,
    );
  if (issue === 62) {
    for (const [id, slug, name] of [
      [103, 'integrais-improprias', 'Integrais impróprias'],
      [106, 'sequencias', 'Sequências'],
    ])
      insert(
        'taxonomy_nodes',
        'id, subject_id, parent_id, kind, slug, name, sort_order, is_published',
        [uuid(3, id), subject, null, 'unit', slug, name, id, true],
      );
    for (const [id, parent, slug, name] of Object.values(taxonomy))
      if (id !== 6)
        insert(
          'taxonomy_nodes',
          'id, subject_id, parent_id, kind, slug, name, sort_order, is_published',
          [
            uuid(3, id),
            subject,
            uuid(3, parent),
            'topic',
            slug,
            name,
            id,
            true,
          ],
        );
  }
  insert('question_sources', 'id, kind, label, licence_note, rights_status', [
    uuid(1, issue),
    'original',
    `Arc — lote autoral #${issue}`,
    'Criado com assistência de Codex para este projeto em 2026-09-07; sem transcrição de banco externo. Aprovação de direitos e revisão independente pendentes.',
    'review_required',
  ]);
  const review = [
    `# Lote #${issue} — ${count} questões para revisão`,
    '',
    'Autoria: Codex, por solicitação do responsável pelo projeto. Data: 2026-09-07.',
    '',
    'Estado: rascunho. Revisor técnico: pendente. Revisão pedagógica e aprovação de direitos: pendentes.',
    '',
    'A alternativa marcada é o gabarito proposto, ainda sujeito à revisão independente.',
    '',
  ];
  for (const [index, item] of batch.entries()) {
    assert(taxonomy[item.topic]);
    assert(['easy', 'medium', 'hard'].includes(item.difficulty));
    assert.equal(new Set(item.options).size, 4);
    assert(item.steps.length >= 2);
    for (const text of [item.statement, ...item.options, ...item.steps]) {
      for (const match of text.matchAll(/\$([^$]+)\$/g))
        katex.renderToString(match[1], {
          throwOnError: true,
          trust: false,
          strict: 'error',
        });
    }
    const number = issue * 100 + index;
    const id = uuid(4, number);
    const shift = index % 4;
    const options = item.options.map(
      (_, i) => item.options[(i - shift + 4) % 4],
    );
    all.push({
      ...item,
      issue,
      id,
      correctIndex: shift,
      options,
      source: {
        kind: 'original',
        author: 'Codex',
        createdAt: '2026-09-07',
        rightsStatus: 'review_required',
        reviewer: null,
      },
      status: 'draft',
    });
    insert(
      'questions',
      'id, subject_id, source_id, kind, difficulty, publication_status, statement_markdown',
      [
        id,
        subject,
        uuid(1, issue),
        'multiple_choice',
        item.difficulty,
        'draft',
        item.statement,
      ],
    );
    options.forEach((option, i) =>
      insert(
        'question_options',
        'id, question_id, label, content_markdown, sort_order',
        [uuid(5, number * 4 + i), id, 'ABCD'[i], option, i + 1],
      ),
    );
    insert('question_answer_keys', 'question_id, correct_option_id', [
      id,
      uuid(5, number * 4 + shift),
    ]);
    insert(
      'question_taxonomy_tags',
      'question_id, taxonomy_node_id, is_primary',
      [id, uuid(3, taxonomy[item.topic][0]), true],
    );
    insert(
      'question_solutions',
      'question_id, final_answer_markdown, explanation_markdown',
      [id, item.options[0], item.steps.join(' ')],
    );
    item.steps.forEach((step, i) =>
      insert(
        'question_solution_steps',
        'id, question_id, title, content_markdown, sort_order',
        [uuid(7, number * 10 + i), id, `Passo ${i + 1}`, step, i + 1],
      ),
    );
    review.push(
      `## ${index + 1}. ${taxonomy[item.topic][3]} — ${item.difficulty}`,
      '',
      `ID: ${id}`,
      '',
      item.statement,
      '',
      ...options.map((option, i) => `${'ABCD'[i]}. ${option}`),
      '',
      `Gabarito proposto: **${'ABCD'[shift]}**`,
      '',
      ...item.steps.map((step, i) => `${i + 1}. ${step}`),
      '',
      'Revisão: [ ] gabarito [ ] distratores [ ] clareza [ ] dificuldade [ ] direitos',
      '',
    );
  }
  sql.push('commit;', '');
  output(
    `supabase/migrations/2026090711${String(issue - 62).padStart(2, '0')}00_draft_calc2_batch_${issue}.sql`,
    sql.join('\n'),
  );
  output(`content/calculus-2/review-${issue}.md`, review.join('\n'));
}
assert.equal(new Set(all.map((item) => item.statement)).size, 84);
output(
  'content/calculus-2/verification.json',
  JSON.stringify(all, null, 2) + '\n',
);
console.log(
  '84 original drafts; 336 alternatives; all mathematical markup renders in KaTeX.',
);
